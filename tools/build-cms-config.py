def folder(name, label, path, fields, icon, create=True, rich=False, **kw):
    c = {
        "name": name,
        "label": label,
        "icon": icon,
        "folder": path,
        "create": create,
        "summary": "{{filename}}",
        "fields": [*fields, body(rich)],
    }
    c.update(kw)
    return c


