"""
Generate docs/admin/config.yml for Sveltia CMS.

Run from the repo root:  python tools/build-cms-config.py

Why a generator: Sveltia has no nested collections, so every leaf folder under
docs/ needs its own collection, and Sveltia drops any frontmatter field that
isn't declared. Hand-maintaining ~30 near-identical blocks is how fields go
missing. Edit the tables below, re-run, commit both files.

Rules baked in (see comments in the output file):
  - Cadwallon bodies are raw-Markdown only (rich text rewrites wikilinks/callouts).
  - Slugs keep Title Case and spaces so [[Wikilinks]] resolve.
  - Everything is `required: false` except the hidden constants, so half-filled
    pages still save.
"""
